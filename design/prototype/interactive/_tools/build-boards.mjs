#!/usr/bin/env node
// Regenerates data/boards.js and board-styles.css from ../project/*.dc.html.
// Plain Node, no dependencies. Run from anywhere:  node design/prototype/interactive/_tools/build-boards.mjs
// The prototype itself needs no build step: it opens straight from file://. Only run this when a board changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const projectDir = path.resolve(root, '../project');
const files = fs.readdirSync(projectDir).filter((f) => f.endsWith('.dc.html')).sort();

// ---- CSS: union of every board's <style> blocks, de-duplicated rule by rule -------------------------------------
function splitRules(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === '{') depth++;
    else if (c === '}') {
      depth--;
      if (depth === 0) { out.push(css.slice(start, i + 1).trim()); start = i + 1; }
    }
  }
  return out.filter(Boolean);
}
const seen = new Map(); // normalised rule -> true
const byPrelude = new Map(); // prelude -> body (conflict check)
const rules = [];
const conflicts = [];
// Largest stylesheet first, so the common block keeps its original order.
const cssByFile = files.map((f) => {
  const s = fs.readFileSync(path.join(projectDir, f), 'utf8');
  const blocks = [...s.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]);
  return { f, css: blocks.join('\n') };
}).sort((a, b) => b.css.length - a.css.length);
for (const { f, css } of cssByFile) {
  for (const r of splitRules(css)) {
    const norm = r.replace(/\s+/g, ' ');
    if (seen.has(norm)) continue;
    const prelude = norm.slice(0, norm.indexOf('{')).trim();
    if (byPrelude.has(prelude) && !prelude.startsWith('@')) conflicts.push(`${prelude} (in ${f})`);
    byPrelude.set(prelude, norm);
    seen.set(norm, true);
    rules.push(r);
  }
}
const header = '/* GENERATED by _tools/build-boards.mjs: union of the <style> blocks of design/prototype/project/*.dc.html. Do not edit by hand. */\n';
fs.writeFileSync(path.join(root, 'board-styles.css'), header + rules.join('\n') + '\n');

// ---- Boards ------------------------------------------------------------------------------------------------------
function extractApp(s) {
  const i = s.indexOf('<div class="app"');
  if (i < 0) return null;
  let depth = 0;
  const re = /<(\/?)div\b[^>]*>/g;
  re.lastIndex = i;
  let m;
  while ((m = re.exec(s))) {
    if (m[1] === '') depth++; else depth--;
    if (depth === 0) return s.slice(i, m.index + 6);
  }
  return null;
}
const boards = {};
for (const f of files) {
  const name = f.replace('.dc.html', '');
  const s = fs.readFileSync(path.join(projectDir, f), 'utf8');
  const app = extractApp(s);
  if (!app) { console.error('no .app in', f); continue; }
  const title = (s.match(/<title>([\s\S]*?)<\/title>/) || [, name])[1].trim();
  const open = app.match(/^<div class="app"[^>]*>/)[0];
  const h = Number((open.match(/min-height:(\d+)px/) || [, 900])[1]);
  let inner = app.slice(open.length, app.length - 6);
  let hdr = null;
  const hm = inner.match(/^\s*<header class="top">([\s\S]*?)<\/header>/);
  if (hm) { hdr = hm[1].trim(); inner = inner.slice(hm[0].length); }
  let kind = 'none';
  // Option A: org pages also have tabs (Projects, Settings), so tabs no longer mean "project bar". A project bar has the project switcher.
  if (hdr) kind = /aria-label="Breadcrumb"/.test(hdr) ? 'run' : /aria-label="Switch project"/.test(hdr) ? 'project' : 'global';
  const fix = (x) => x
    .replace(/href="([A-Za-z0-9]+)\.dc\.html"/g, 'href="#/b/$1"')
    .replace(/href="https:\/\/github\.com\/"/g, 'href="https://github.com/" target="_blank" rel="noopener"');
  boards[name] = { title, h, kind, header: hdr ? fix(hdr) : null, body: fix(inner.trim()) };
}
const js = '/* GENERATED by _tools/build-boards.mjs from design/prototype/project/*.dc.html. Do not edit by hand. */\n' +
  'window.AD_BOARDS = ' + JSON.stringify(boards) + ';\n';
fs.writeFileSync(path.join(root, 'data/boards.js'), js);
console.log(`boards: ${Object.keys(boards).length}, css rules: ${rules.length}, bytes: ${js.length}`);
if (conflicts.length) console.log('same selector with different body (later one wins):\n  ' + conflicts.join('\n  '));
